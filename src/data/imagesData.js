/**
 * Maps a given crop name (and optional type) to the authentic matching agricultural photograph.
 */
export function getCropImage(name, type = '') {
  if (!name) return IMAGES.crops.default;
  const n = name.toLowerCase();
  const t = (type || '').toLowerCase();

  // 1. Wheat
  if (n.includes('wheat')) {
    return IMAGES.crops.Wheat;
  }

  // 2. Basmati Rice / Paddy
  if (n.includes('rice') || n.includes('basmati') || n.includes('paddy')) {
    return IMAGES.crops.Rice || IMAGES.crops['Paddy / Basmati Rice'];
  }

  // 3. Mustard
  if (n.includes('mustard') || n.includes('sarson')) {
    return IMAGES.crops.Mustard;
  }

  // 4. Moong Dal / Chickpea / Gram / Pulses / Arhar / Tur / Lentils / Guar
  if (
    n.includes('moong') ||
    n.includes('dal') ||
    n.includes('gram') ||
    n.includes('chickpea') ||
    n.includes('arhar') ||
    /\btur\b/i.test(n) ||
    n.includes('pigeonpea') ||
    n.includes('lentil') ||
    n.includes('guar') ||
    t.includes('pulse') ||
    t.includes('legume')
  ) {
    return IMAGES.crops.Moong || IMAGES.crops['Chickpea / Gram'];
  }

  // 5. Sugarcane
  if (n.includes('sugarcane') || n.includes('cane')) {
    return IMAGES.crops.Sugarcane;
  }

  // 6. Cotton / Jute / Plant Fiber
  if (n.includes('cotton') || n.includes('jute') || t.includes('fiber')) {
    return IMAGES.crops.Cotton;
  }

  // 7. Citrus / Mandarin / Kinnow / Orange
  if (
    n.includes('mandarin') ||
    n.includes('kinnow') ||
    n.includes('citrus') ||
    n.includes('orange')
  ) {
    return IMAGES.crops.Citrus || IMAGES.crops['Citrus / Orange'];
  }

  // 8. Mango
  if (n.includes('mango')) {
    return IMAGES.crops.Mango;
  }

  // 9. Pomegranate
  if (n.includes('pomegranate')) {
    return IMAGES.crops.Pomegranate;
  }

  // 10. Banana
  if (n.includes('banana')) {
    return IMAGES.crops.Banana;
  }

  // 11. Coconut
  if (n.includes('coconut') || t.includes('plantation')) {
    return IMAGES.crops.Coconut;
  }

  // 12. Grapes
  if (n.includes('grape')) {
    return IMAGES.crops.Grapes;
  }

  // 13. Pear & Peach & Mulberry
  if (n.includes('pear') || n.includes('peach') || n.includes('mulberry')) {
    return IMAGES.crops.Pear;
  }

  // 14. Tomato / Chilli
  if (n.includes('tomato') || n.includes('chilli')) {
    return IMAGES.crops.Tomato;
  }

  // 15. Potato / Peas / Tubers
  if (n.includes('potato') || n.includes('pea') || t.includes('tuber')) {
    return IMAGES.crops.Potato;
  }

  // 16. Soybean
  if (n.includes('soybean') || n.includes('soya')) {
    return IMAGES.crops.Soybean;
  }

  // 17. Sunflower / Flowers / Marigold
  if (
    n.includes('sunflower') ||
    n.includes('marigold') ||
    n.includes('chrysanthemum') ||
    t.includes('flower')
  ) {
    return IMAGES.crops.Sunflower;
  }

  // 18. Onion / Garlic
  if (n.includes('onion') || n.includes('garlic')) {
    return IMAGES.crops.Onion;
  }

  // 19. Maize / Corn / Sorghum
  if (n.includes('maize') || n.includes('corn') || n.includes('sorghum')) {
    return IMAGES.crops.Maize;
  }

  // 20. Millets / Bajra / Ragi / Barley
  if (
    n.includes('millet') ||
    n.includes('bajra') ||
    n.includes('ragi') ||
    n.includes('barley') ||
    t.includes('millet')
  ) {
    return IMAGES.crops.Millets;
  }

  // 21. Spices (Turmeric, Cumin, Jeera, Fennel, Saunf, Castor)
  if (
    n.includes('turmeric') ||
    n.includes('cumin') ||
    n.includes('jeera') ||
    n.includes('fennel') ||
    n.includes('saunf') ||
    n.includes('castor') ||
    t.includes('spice')
  ) {
    return IMAGES.crops.Spices;
  }

  // Fallback: search individual tokens in existing IMAGES.crops keys
  for (const [key, url] of Object.entries(IMAGES.crops)) {
    if (key === 'default') continue;
    const parts = key.split(/[\s,/]+/).filter((p) => p.length > 2);
    if (parts.some((part) => n.includes(part.toLowerCase()))) {
      return url;
    }
  }

  return IMAGES.crops.default;
}

export function getProductImage(product) {
  if (!product) return IMAGES.products.default;
  if (product.imageUrl) return product.imageUrl;
  if (IMAGES.products[product.id]) return IMAGES.products[product.id];
  return getCropImage(product.title) || IMAGES.products.default;
}

export function getSchemeImage(schemeId) {
  return IMAGES.schemes[schemeId] || IMAGES.schemes.default;
}
