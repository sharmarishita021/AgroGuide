export function getCropImage(name) {
  if (!name) return IMAGES.crops.default;
  for (const [key, url] of Object.entries(IMAGES.crops)) {
    if (name.toLowerCase().includes(key.toLowerCase())) {
      return url;
    }
  }
  return IMAGES.crops.default;
}

export function getProductImage(product) {
  if (!product) return IMAGES.products.default;
  if (product.imageUrl) return product.imageUrl;
  if (IMAGES.products[product.id]) return IMAGES.products[product.id];
  return getCropImage(product.title) || IMAGES.products.default;
}

export function getSchemeImage(schemeId) {
  return IMAGES.schemes[schemeId] || IMAGES.schemes.default;
}
